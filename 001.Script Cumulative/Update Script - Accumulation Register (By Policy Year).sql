CREATE PROCEDURE QAccReg(@P_PANO as Integer) 
AS 
SELECT ACCEPTANCE.REGID, ACCEPTANCE.FLDID, ACCEPTANCE.VALUEID, ACCEPTANCE.ATYPE, ACCEPTANCE.ASTATUS, ACCEPTANCE.PANO, 
ACCEPTANCE.NORISKACCUMULATIONF, YEAR(RARRHEADER.RDATE) AS RYEAR
FROM ACCEPTANCE, RARRHEADER
WHERE ACCEPTANCE.ANO=@P_PANO AND RARRHEADER.ANO=ACCEPTANCE.ANO 
 
GO


