IF EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'FNTOI_genHtab') AND type IN ( N'FN', N'IF', N'TF', N'FS', N'FT' ) )
BEGIN

DROP FUNCTION FNTOI_genHtab
end
GO
CREATE FUNCTION FNTOI_genHtab (@P_TOI AS VARCHAR(10))                
RETURNS Table                
AS RETURN (      
  
SELECT  TOP 1         
TOI.TOI,        
TOI.FLDID1, TOI.FLDTAG1, GENHTAB_1.FLDCRITERIA AS FLDCRITERIA1,   
TOI.FLDID2, TOI.FLDTAG2, GENHTAB_2.FLDCRITERIA AS FLDCRITERIA2,   
TOI.FLDID3, TOI.FLDTAG3, GENHTAB_3.FLDCRITERIA AS FLDCRITERIA3,   
TOI.FLDID4, TOI.FLDTAG4, GENHTAB_4.FLDCRITERIA AS FLDCRITERIA4,   
TOI.FLDID5, TOI.FLDTAG5, GENHTAB_5.FLDCRITERIA AS FLDCRITERIA5,  
TOI.FLDID6, TOI.FLDTAG6, GENHTAB_6.FLDCRITERIA AS FLDCRITERIA6,  
TOI.FLDID7, TOI.FLDTAG7, GENHTAB_7.FLDCRITERIA AS FLDCRITERIA7,   
TOI.FLDID8, TOI.FLDTAG8, GENHTAB_8.FLDCRITERIA AS FLDCRITERIA8,  
TOI.FLDID9, TOI.FLDTAG9, GENHTAB_9.FLDCRITERIA AS FLDCRITERIA9,   
TOI.FLDID10, TOI.FLDTAG10, GENHTAB_10.FLDCRITERIA AS FLDCRITERIA10,  
TOI.FLDID11, TOI.FLDTAG11, GENHTAB_11.FLDCRITERIA AS FLDCRITERIA11,   
TOI.FLDID12, TOI.FLDTAG12, GENHTAB_12.FLDCRITERIA AS FLDCRITERIA12,    
TOI.FLDID13, TOI.FLDTAG13, GENHTAB_13.FLDCRITERIA AS FLDCRITERIA13,   
TOI.FLDID14, TOI.FLDTAG14, GENHTAB_14.FLDCRITERIA AS FLDCRITERIA14,   
TOI.FLDID15, TOI.FLDTAG15, GENHTAB_15.FLDCRITERIA AS FLDCRITERIA15  
FROM         
TOI         
LEFT OUTER JOIN GENHTAB as GENHTAB_1 ON TOI.FLDID1<>'' AND TOI.FLDID1 = GENHTAB_1.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_2 ON TOI.FLDID2<>'' AND TOI.FLDID2 = GENHTAB_2.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_3 ON TOI.FLDID3<>'' AND TOI.FLDID3 = GENHTAB_3.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_4 ON TOI.FLDID4<>'' AND TOI.FLDID4 = GENHTAB_4.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_5 ON TOI.FLDID5<>'' AND TOI.FLDID5 = GENHTAB_5.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_6 ON TOI.FLDID6<>'' AND TOI.FLDID6 = GENHTAB_6.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_7 ON TOI.FLDID7<>'' AND TOI.FLDID7 = GENHTAB_7.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_8 ON TOI.FLDID8<>'' AND TOI.FLDID8 = GENHTAB_8.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_9 ON TOI.FLDID9<>'' AND TOI.FLDID9 = GENHTAB_9.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_10 ON TOI.FLDID10<>'' AND TOI.FLDID10 = GENHTAB_10.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_11 ON TOI.FLDID11<>'' AND TOI.FLDID11 = GENHTAB_11.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_12 ON TOI.FLDID12<>'' AND TOI.FLDID12 = GENHTAB_12.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_13 ON TOI.FLDID13<>'' AND TOI.FLDID13 = GENHTAB_13.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_14 ON TOI.FLDID14<>'' AND TOI.FLDID14 = GENHTAB_14.FLDID         
LEFT OUTER JOIN GENHTAB as GENHTAB_15 ON TOI.FLDID15<>'' AND TOI.FLDID15 = GENHTAB_15.FLDID         
WHERE  TOI.TOI lIKE @P_TOI   
)  

GO

