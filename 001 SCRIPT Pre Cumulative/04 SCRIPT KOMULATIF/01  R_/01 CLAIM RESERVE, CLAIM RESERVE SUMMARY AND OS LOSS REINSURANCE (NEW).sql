Create FUNCTION R_OS_CLAIM_PAYMENT( @P_EDate as  smalldatetime)                  
RETURNS @OS_CLAIM TABLE (OCNO int, Payment Varchar(10), ANO int, CNO int, CURRENCY varchar(10), TOC varchar(10), Branch Varchar(10), ISType varchar(1), ClaimNo varchar(20), GROSS_OS Float, GROSS_LOSS float, GROSS_SETTLED float, SETTLEDF bit, EXPENSE_OS Float)      
AS      
BEGIN      
      
insert into @OS_Claim          
SELECT OCNO, PAYMENT, ANO, CNO, CURRENCY, TOC, BRANCH, ISTYPE, CLAIMNO, GROSS_OS, GROSS_LOSS, GROSS_SETTLED, 0 as SETTLEDF, 0 as EXPENSE_OS    
FROM OS_CLAIM_BY_DETAIL_LOSS_PAYMENT(@P_EDATE)              
      
insert into @OS_Claim              


Select           
 CLAIM.OCNO, COALESCE(CLLOSS.PAYMENT, CLDED.ID) AS PAYMENT, CLAIM.ANO, CLAIM.CNO, COALESCE(CLLOSS.CURRENCY, CLDED.CURRENCY), CLAIM.TOC, ACCEPTANCE.BRANCH, CLAIM.ISTYPE, CLAIM.CLAIMNO,            
 0 as GROSS_OS,        
  
(CLLOSS.ESTIMATE*CCALC.SHARE/100) AS GROSS_LOSS,       
  
 Case When CLAIM.PCStatus='P' and Month(Claim.CSDate)=MONTH(@P_EDATE) and Year(Claim.CSDate)=Year(@P_EDate) then        
 0      
 else        
  (CLLOSS.AMOUNT*CCALC.SHARE/100)  
 End AS GROSS_SETTLED,      
 
 
 1 as SETTLEDF,    
 0 as EXPENSE_OS    
  
FROM CLAIM 
INNER JOIN CCALC ON (CCALC.CNO=CLAIM.CNO) 
LEFT JOIN CLAIM PCLAIM ON (PCLAIM.CNO=CLAIM.PCNO)
