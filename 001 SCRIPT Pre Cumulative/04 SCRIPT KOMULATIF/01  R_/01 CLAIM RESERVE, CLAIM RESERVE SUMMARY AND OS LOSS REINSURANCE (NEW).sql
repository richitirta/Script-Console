select R2.ID, 'S2' as Type, O.ANO, O.OCNO, R1.DOCNO as REFNO, R1.DESCRIPTION, O.CURRENCY, O.TOC, SUM(R2.SHARE/100*O.GROSS_OS*R.SP2SHARE/100) AS RESERVED from @OS_CLAIM_BY_DETAIL O, RArrHeader R, Reinsurance R1, RPart R2       
