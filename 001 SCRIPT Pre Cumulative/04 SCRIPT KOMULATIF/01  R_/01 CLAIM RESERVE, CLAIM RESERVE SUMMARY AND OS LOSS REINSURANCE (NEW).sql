Left Join Claim NClaim On (NClaim.pCNO=Claim.CNO and NClaim.CSeqNo=Claim.CSeqNo)
Where Claim.CStatus in ('C','A') and Claim.CType in ('N','E','C') and Claim.PCstatus in ('','A') and Claim.ADate Between @P_SDate and @P_EDate and Claim.pSettledF=0 and NClaim.CSeqNo is null
            
