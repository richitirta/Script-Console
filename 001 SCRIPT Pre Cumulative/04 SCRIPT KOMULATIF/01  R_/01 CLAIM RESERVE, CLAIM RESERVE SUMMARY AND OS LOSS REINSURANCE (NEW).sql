from Claim INNER JOIN CCALC ON (CCALC.CNO=CLAIM.CNO) 
LEFT JOIN (SELECT CNO, CURRENCY, MAX(NOC) AS NOC, MAX(PAYMENT) AS PAYMENT FROM CLLOSS GROUP BY CNO, CURRENCY) CLLOSS ON (CLLOSS.CNO=CLAIM.CNO AND CLLOSS.CURRENCY=CCALC.CURRENCY)
INNER JOIN ACCEPTANCE ON (ACCEPTANCE.ANO=CLAIM.ANO) INNER JOIN CARRHEADER ON (CARRHEADER.CNO=CLAIM.CNO)    
Where Claim.PSettledF=0 and    
(    
(Claim.CType='C' and Claim.CStatus not in ('R','P','T') and Claim.ADate Between @P_SDate and @P_EDate) Or    
(Claim.Cstatus='C' and Claim.PCStatus='R' and Claim.VSeqNo>1 and Claim.CSDate Between @P_SDate and @P_EDate) Or    
(Claim.Cstatus='C' and Claim.PCStatus='P' and Claim.CSDate Between @P_SDate and @P_EDate) Or    
(Claim.SettledF=1 and Claim.CStatus in ('C','A') and Claim.PCStatus='' and Claim.ADate Between @P_SDate and @P_EDate) or    
(Claim.SettledF=1 and Claim.CStatus='C' and Claim.PCStatus='A' and Claim.CSDate Between @P_SDate and @P_EDate)    
)    
)    
    
    

    
   
