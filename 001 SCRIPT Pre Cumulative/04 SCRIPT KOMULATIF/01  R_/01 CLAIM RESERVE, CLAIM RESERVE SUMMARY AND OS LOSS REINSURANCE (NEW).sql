CREATE FUNCTION OS_CLAIM_BY_DETAIL_BY_RATECODE( @P_EDate as  smalldatetime)                          
RETURNS TABLE                           
AS RETURN (                          
SELECT                          
 CLAIM.OCNO, CLAIM.PAYMENT, CLAIM.ANO, CLAIM.CNO, LCALC.CODE, LCALC.CURRENCY,CLAIM.TOC, ACCEPTANCE.BRANCH,CURRENCY.RATE, CLAIM.ISTYPE, CLAIM.CLAIMNO,                    
    
 (CASE                          
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN            
  ((LCALC.LOSS-LCALC.EDEDUCTIBLE-LCALC.SALVAGE)*R.PCTSHARE/100)      
 ELSE                          
  CASE                           
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN            
   ((LCALC.LOSS-LCALC.EDEDUCTIBLE-LCALC.SALVAGE)*R.PCTSHARE/100)-(CASE WHEN PLCALC.CNO IS NOT NULL THEN ((PLCALC.INDEMNITY-PLCALC.DEDUCTIBLE-PLCALC.SALVAGE)*PR.PCTSHARE/100) ELSE 0 END)                          
  ELSE                          
    ((LCALC.LOSS-LCALC.EDEDUCTIBLE-LCALC.SALVAGE)*R.PCTSHARE/100)-((LCALC.INDEMNITY-LCALC.DEDUCTIBLE+-LCALC.SALVAGE)*R.PCTSHARE/100)                        
  END                          
 end) as GROSS_OS,        
  
 (CASE                          
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN            
  ((LCALC.LOSS-LCALC.EDEDUCTIBLE-LCALC.SALVAGE)*R.PCTSHARE/100)*CH.ERETENTION/100     
 ELSE                          
  CASE                           
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN            
   ((LCALC.LOSS-LCALC.EDEDUCTIBLE-LCALC.SALVAGE)*R.PCTSHARE/100)*CH.ERETENTION/100-(CASE WHEN PLCALC.CNO IS NOT NULL THEN ((PLCALC.INDEMNITY-PLCALC.DEDUCTIBLE-PLCALC.SALVAGE)*PR.PCTSHARE/100)*PCH.RETENTION/100 ELSE 0 END)                          
  ELSE                          
    ((LCALC.LOSS-LCALC.EDEDUCTIBLE-LCALC.SALVAGE)*R.PCTSHARE/100)*CH.ERETENTION/100-((LCALC.INDEMNITY-LCALC.DEDUCTIBLE+-LCALC.SALVAGE)*R.PCTSHARE/100)*CH.RETENTION/100       
                 
  END                          
 end) as GROSS_OS_NET,   
  
 (CASE                          
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN            
  ((LCALC.LOSS-LCALC.EDEDUCTIBLE-LCALC.SALVAGE)*R.PCTSHARE/100)*(CH.XL1ESHARE+CH.XL2ESHARE+CH.XL3ESHARE+CH.XL4ESHARE+CH.XL5ESHARE+CH.XL6ESHARE+CH.XL7ESHARE)/100     
 ELSE                          
  CASE                           
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN            
   ((LCALC.LOSS-LCALC.EDEDUCTIBLE-LCALC.SALVAGE)*R.PCTSHARE/100)*(CH.XL1ESHARE+CH.XL2ESHARE+CH.XL3ESHARE+CH.XL4ESHARE+CH.XL5ESHARE+CH.XL6ESHARE+CH.XL7ESHARE)/100  
    -(CASE WHEN PLCALC.CNO IS NOT NULL THEN ((PLCALC.INDEMNITY-PLCALC.DEDUCTIBLE-PLCALC.SALVAGE)*PR.PCTSHARE/100)*(PCH.XL1SHARE+PCH.XL2SHARE+PCH.XL3SHARE+PCH.XL4SHARE+PCH.XL5SHARE+PCH.XL6SHARE+PCH.XL7SHARE)/100 ELSE 0 END)                          
  ELSE                          
    ((LCALC.LOSS-LCALC.EDEDUCTIBLE-LCALC.SALVAGE)*R.PCTSHARE/100)*(CH.XL1ESHARE+CH.XL2ESHARE+CH.XL3ESHARE+CH.XL4ESHARE+CH.XL5ESHARE+CH.XL6ESHARE+CH.XL7ESHARE)/100  
    -((LCALC.INDEMNITY-LCALC.DEDUCTIBLE+-LCALC.SALVAGE)*R.PCTSHARE/100)*(CH.XL1SHARE+CH.XL2SHARE+CH.XL3SHARE+CH.XL4SHARE+CH.XL5SHARE+CH.XL6SHARE+CH.XL7SHARE)/100                        
  END                          
 end) as GROSS_OS_XOL,                          
                          
 ((LCALC.LOSS-LCALC.EDEDUCTIBLE-LCALC.SALVAGE)*R.PCTSHARE/100) AS GROSS_LOSS,      
 ((LCALC.LOSS-LCALC.EDEDUCTIBLE-LCALC.SALVAGE)*R.PCTSHARE/100)*CH.ERETENTION/100 AS GROSS_LOSS_NET,  
 ((LCALC.LOSS-LCALC.EDEDUCTIBLE-LCALC.SALVAGE)*R.PCTSHARE/100)*(CH.XL1ESHARE+CH.XL2ESHARE+CH.XL3ESHARE+CH.XL4ESHARE+CH.XL5ESHARE+CH.XL6ESHARE+CH.XL7ESHARE)/100 AS GROSS_LOSS_XOL,  
                          
 (CASE                          
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE)  OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN                          
  0                           
 ELSE                          
  CASE                           
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN                      
        
   (CASE WHEN PLCALC.CNO IS NOT NULL THEN ((PLCALC.INDEMNITY-PLCALC.DEDUCTIBLE-PLCALC.SALVAGE)*PR.PCTSHARE/100) ELSE 0 END)                          
  ELSE                          
   ((LCALC.INDEMNITY-LCALC.DEDUCTIBLE+-LCALC.SALVAGE)*R.PCTSHARE/100)                        
  END                          
 end) as GROSS_SETTLED,    
  
  
 (CASE                          
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE)  OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN                          
  0                           
 ELSE                          
  CASE                           
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN                      
        
   (CASE WHEN PLCALC.CNO IS NOT NULL THEN ((PLCALC.INDEMNITY-PLCALC.DEDUCTIBLE-PLCALC.SALVAGE)*PR.PCTSHARE/100)*PCH.RETENTION/100 ELSE 0 END)                          
  ELSE                          
   ((LCALC.INDEMNITY-LCALC.DEDUCTIBLE+-LCALC.SALVAGE)*R.PCTSHARE/100)*CH.RETENTION/100  
  END                          
 end) as GROSS_SETTLED_NET,    
  
(CASE                          
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE)  OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN                          
  0                           
 ELSE                          
  CASE                           
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN                      
        
   (CASE WHEN PLCALC.CNO IS NOT NULL THEN ((PLCALC.INDEMNITY-PLCALC.DEDUCTIBLE-PLCALC.SALVAGE)*PR.PCTSHARE/100)*(PCH.XL1SHARE+PCH.XL2SHARE+PCH.XL3SHARE+PCH.XL4SHARE+PCH.XL5SHARE+PCH.XL6SHARE+PCH.XL7SHARE)/100 ELSE 
0 END)                          
  ELSE                          
   ((LCALC.INDEMNITY-LCALC.DEDUCTIBLE+-LCALC.SALVAGE)*R.PCTSHARE/100)*(CH.XL1SHARE+CH.XL2SHARE+CH.XL3SHARE+CH.XL4SHARE+CH.XL5SHARE+CH.XL6SHARE+CH.XL7SHARE)/100                        
  END                          
 end) as GROSS_SETTLED_XOL,  
 
 (CASE                          
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN            
  ((LCALC.LOSS)*R.PCTSHARE/100)      
 ELSE                          
  CASE                           
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN            
   ((LCALC.LOSS)*R.PCTSHARE/100)-(CASE WHEN PLCALC.CNO IS NOT NULL THEN ((PLCALC.INDEMNITY)*PR.PCTSHARE/100) ELSE 0 END)                          
  ELSE                          
    ((LCALC.LOSS)*R.PCTSHARE/100)-((LCALC.INDEMNITY)*R.PCTSHARE/100)                        
  END                          
 end) as LOSS_OS,
 
 (CASE                          
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN            
  0
 ELSE                          
  CASE                           
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN            
   (CASE WHEN PLCALC.CNO IS NOT NULL THEN ((PLCALC.INDEMNITY)*PR.PCTSHARE/100) ELSE 0 END)                          
  ELSE                          
   ((LCALC.INDEMNITY)*R.PCTSHARE/100)                        
  END                          
 end) as LOSS_Settled, 
 
 (CASE                          
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN            
  ((-LCALC.EDEDUCTIBLE)*R.PCTSHARE/100)      
 ELSE                          
  CASE                           
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN            
   ((-LCALC.EDEDUCTIBLE)*R.PCTSHARE/100)-(CASE WHEN PLCALC.CNO IS NOT NULL THEN ((-PLCALC.DEDUCTIBLE)*PR.PCTSHARE/100) ELSE 0 END)                          
  ELSE                          
    ((-LCALC.EDEDUCTIBLE)*R.PCTSHARE/100)-((-LCALC.DEDUCTIBLE)*R.PCTSHARE/100)                        
  END                          
 end) as DEDUCTIBLE_OS,

 (CASE                          
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN            
  0
 ELSE                          
  CASE                           
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN            
   (CASE WHEN PLCALC.CNO IS NOT NULL THEN ((-PLCALC.DEDUCTIBLE)*PR.PCTSHARE/100) ELSE 0 END)                          
  ELSE                          
    ((-LCALC.DEDUCTIBLE)*R.PCTSHARE/100)                        
  END                          
 end) as DEDUCTIBLE_Settled,
 
 (CASE                          
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN            
  ((-LCALC.SALVAGE)*R.PCTSHARE/100)      
 ELSE                          
  CASE                           
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN            
   ((-LCALC.SALVAGE)*R.PCTSHARE/100)-(CASE WHEN PLCALC.CNO IS NOT NULL THEN ((-PLCALC.SALVAGE)*PR.PCTSHARE/100) ELSE 0 END)                          
  ELSE                          
    ((-LCALC.SALVAGE)*R.PCTSHARE/100)-((-LCALC.SALVAGE)*R.PCTSHARE/100)                        
  END                          
 end) as SALVAGE_OS,
 
 (CASE                          
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN            
  0
 ELSE                          
  CASE                           
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN NCLAIM.CSEQNO IS NULL AND CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN            
   (CASE WHEN PLCALC.CNO IS NOT NULL THEN ((-PLCALC.SALVAGE)*PR.PCTSHARE/100) ELSE 0 END)                          
  ELSE                          
   ((-LCALC.SALVAGE)*R.PCTSHARE/100)                        
  END                          
 end) as SALVAGE_Settled

         
FROM CLAIM   
INNER JOIN LCALC ON (LCALC.CNO=CLAIM.CNO)   
INNER JOIN RARRHEADER R ON (R.ANO=CLAIM.ANO)
INNER JOIN CARRHEADER CH ON (CH.CNO=CLAIM.CNO)  
LEFT JOIN Claim NClaim On (NClaim.pCNO=Claim.CNO and NClaim.CSeqNo=Claim.CSeqNo)
LEFT JOIN CLAIM PCLAIM ON (PCLAIM.CNO=CLAIM.PCNO)
LEFT JOIN RARRHEADER PR ON (R.ANO=PCLAIM.ANO)
LEFT JOIN LCALC PLCALC ON (PLCALC.CNO=CLAIM.PCNO AND PLCALC.CURRENCY=LCALC.CURRENCY)                          
LEFT JOIN CARRHEADER  PCH ON (PCH.CNO=CLAIM.PCNO)  
INNER JOIN ACCEPTANCE ON (ACCEPTANCE.ANO=CLAIM.ANO)   
INNER JOIN fn_exchange(@P_EDate) as Currency On (Currency.Currency=LCALC.Currency)              
WHERE                           
 CLAIM.REGDATE<=@P_EDATE AND (CLAIM.CTYPE<>'C' OR (CLAIM.CTYPE='C' AND CLAIM.CSTATUS in ('A','C') AND CLAIM.ADATE>@P_EDate) OR CLAIM.CSTATUS in ('P','T')) AND CLAIM.CSTATUS<>'R' AND          
 ((CLAIM.SETTLEDF=0 AND CLAIM.CSDATE<=@P_EDATE AND CLAIM.CSTATUS<>'C') OR                           
  (CLAIM.PSETTLEDF=0 AND CLAIM.CSDATE>@P_EDATE AND (CLAIM.PCSTATUS in ('P','A') or CLAIM.SETTLEDF=0 OR CLAIM.ADATE>@P_EDATE)))                                  
)                          
       
