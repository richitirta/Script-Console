CREATE FUNCTION R_OS_CLAIM_DETAIL( @P_EDate as  smalldatetime)        
RETURNS @R_OS_CLAIM_DETAIL TABLE (ID varchar(10), Type varchar(2), ANO int, OCNO int, REFNO varchar(20), Description varchar(255), Currency varchar(10), TOC varchar(10), Reserved Float)      
AS      
BEGIN      
      
Declare @OS_CLAIM_BY_DETAIL Table(Payment varchar(10), CNO int, ANO int, OCNO int, Currency varchar(10), TOC varchar(10), ISType varchar(2), ClaimNo varchar(20), Gross_Loss Float, Gross_OS Float, Expense_OS Float, Cost_OS Float, Gross_Settled Float)      
insert into @OS_CLAIM_BY_DETAIL      
    
Select O.Payment, O.CNO, O.ANO, C.OCNO, SysTab.Currency, O.TOC, O.ISType, O.ClaimNo, O.Gross_Loss*O.Rate as Gross_Loss, O.Gross_OS*O.Rate as Gross_OS, O.Expense_OS*O.Rate as Expense_OS, O.Cost_OS*O.Rate as Cost_OS, O.Gross_Settled*O.Rate as Gross_Settled    
from OS_CLAIM_BY_DETAIL(@P_EDATE) O, Claim C, SysTab    
Where C.CNO=O.CNO
      

-- INWARD BUSINESS      
Insert into @R_OS_CLAIM_DETAIL            
select O.Payment as ID, Case When O.ISType in ('C','L') then 'DI' else (Case When O.ISType in ('I') then 'IC' else (Case When O.ISType in ('R') then 'IR' else 'IT' end) end) end as Type, O.ANO, O.OCNO, O.CLAIMNO as REFNO, '--' as Description, O.CURRENCY, O.TOC, SUM(O.GROSS_OS-O.COST_OS) AS RESERVED       
from @OS_CLAIM_BY_DETAIL O, RArrheader R Where R.ANO=O.ANO
GROUP BY O.Payment, Case When O.ISType in ('C','L') then 'DI' else (Case When O.ISType in ('I') then 'IC' else (Case When O.ISType in ('R') then 'IR' else 'IT' end) end) end, O.ANO, O.OCNO, O.CLAIMNO, O.CURRENCY, O.TOC        

Insert into @R_OS_CLAIM_DETAIL  
select O.Payment as ID, 'CF' as Type, O.ANO, O.OCNO, O.CLAIMNO as REFNO, '--' as Description, O.CURRENCY, O.TOC, SUM(O.GROSS_OS*-R.MShare/100) AS RESERVED       
from @OS_CLAIM_BY_DETAIL O, RArrheader R Where R.ANO=O.ANO
GROUP BY O.Payment, O.ANO, O.OCNO, O.CLAIMNO, O.CURRENCY, O.TOC        

union All

select O.Payment as ID, 'OP' as Type, O.ANO, O.OCNO, O.CLAIMNO as REFNO, '--' as Description, O.CURRENCY, O.TOC, SUM(O.EXPENSE_OS+O.COST_OS) AS RESERVED       
from @OS_CLAIM_BY_DETAIL O, RArrheader R Where R.ANO=O.ANO
GROUP BY O.Payment, O.ANO, O.OCNO, O.CLAIMNO, O.CURRENCY, O.TOC   
Having SUM(O.EXPENSE_OS+O.COST_OS)<>0     
      
union all      
      
-- OUTWARD BUSINESS      
-- Compulsory      
select R2.ID, 'CP' as Type, O.ANO, O.OCNO, R1.DOCNO as REFNO, R1.DESCRIPTION, O.CURRENCY, O.TOC, SUM(R2.SHARE/100*O.GROSS_OS*R.CSHARE/100) AS RESERVED from @OS_CLAIM_BY_DETAIL O, RArrHeader R, Reinsurance R1, RPart R2       
Where O.ANO=R.ANO and R1.RID=R.CID and R2.RNO=R1.RNO and R.CSHARE<>0 GROUP BY R2.ID, O.ANO, O.OCNO, R1.DOCNO, R1.DESCRIPTION, O.CURRENCY, O.TOC        
      
union all       
      
      
-- Excess Priority      
        
select R2.ID, 'XP' as Type, O.ANO, O.OCNO, R1.DOCNO as REFNO, R1.DESCRIPTION, O.CURRENCY, O.TOC, SUM(R2.SHARE/100*O.GROSS_OS*R.XPSHARE/100) AS RESERVED from @OS_CLAIM_BY_DETAIL O, RArrHeader R, Reinsurance R1, RPart R2       
Where O.ANO=R.ANO and R1.RID=R.XPID and R2.RNO=R1.RNO and R.XPSHARE<>0 GROUP BY R2.ID, O.ANO, O.OCNO, R1.DOCNO, R1.DESCRIPTION, O.CURRENCY, O.TOC        
      
union all      
      
-- Decree      
        
select R2.ID, 'DC' as Type, O.ANO, O.OCNO, R1.DOCNO as REFNO, R1.DESCRIPTION, O.CURRENCY, O.TOC, SUM(R2.SHARE/100*O.GROSS_OS*R.DSHARE/100) AS RESERVED from @OS_CLAIM_BY_DETAIL O, RArrHeader R, Reinsurance R1, RPart R2       
Where O.ANO=R.ANO and R1.RID=R.DID and R2.RNO=R1.RNO and R.DSHARE<>0 GROUP BY R2.ID, O.ANO, O.OCNO, R1.DOCNO, R1.DESCRIPTION, O.CURRENCY, O.TOC        
      
union all      
      
-- Quota Share        
        
select R2.ID, 'QS' as Type, O.ANO, O.OCNO, R1.DOCNO as REFNO, R1.DESCRIPTION, O.CURRENCY, O.TOC, SUM(R2.SHARE/100*O.GROSS_OS*R.QSHARE/100) AS RESERVED from @OS_CLAIM_BY_DETAIL O, RArrHeader R, Reinsurance R1, RPart R2       
Where O.ANO=R.ANO and R1.RID=R.QID and R2.RNO=R1.RNO and R.QSHARE<>0 GROUP BY R2.ID, O.ANO, O.OCNO, R1.DOCNO, R1.DESCRIPTION, O.CURRENCY, O.TOC        
        
union all        
        
-- Surplus #1        
        
select R2.ID, 'S1' as Type, O.ANO, O.OCNO, R1.DOCNO as REFNO, R1.DESCRIPTION, O.CURRENCY, O.TOC, SUM(R2.SHARE/100*O.GROSS_OS*R.SP1SHARE/100) AS RESERVED from @OS_CLAIM_BY_DETAIL O, RArrHeader R, Reinsurance R1, RPart R2       
Where O.ANO=R.ANO and R1.RID=R.SP1ID and R2.RNO=R1.RNO and R.SP1SHARE<>0 GROUP BY R2.ID, O.ANO, O.OCNO, R1.DOCNO, R1.DESCRIPTION, O.CURRENCY, O.TOC        
        
union all        
        
