Create FUNCTION R_OS_CLAIM_EXPENSE( @P_EDate as  smalldatetime)                
RETURNS @OS_CLAIM TABLE (OCNO int, CCTYPE Varchar(10), Payment Varchar(10), ANO int, CNO int, CURRENCY varchar(10), TOC varchar(10), Branch Varchar(10), ISType varchar(1), ClaimNo varchar(20), GROSS_OS Float, GROSS_LOSS float, GROSS_SETTLED float, SETTLEDF bit,EXPENSE_OS Float)    
AS    
BEGIN    
    
insert into @OS_Claim        
SELECT OCNO, CCTYPE, PAYMENT, ANO, CNO, CURRENCY, TOC, BRANCH, ISTYPE, CLAIMNO, GROSS_OS, GROSS_LOSS, GROSS_SETTLED, 0 as SETTLEDF, EXPENSE_OS  
FROM OS_CLAIM_BY_DETAIL_LOSS_EXPENSE(@P_EDATE)            
    
insert into @OS_Claim            
Select         
 CLAIM.OCNO, CLCOST.CCTYPE, CLCOST.ID AS PAYMENT, CLAIM.ANO, CLAIM.CNO, CLCOST.CURRENCY, CLAIM.TOC, ACCEPTANCE.BRANCH, CLAIM.ISTYPE, CLAIM.CLAIMNO,          
 0 as GROSS_OS,      

(CLCOST.ESTIMATE*(CASE WHEN CLCOST.CONTRIBUTIONF=1 THEN CCALC.SHARE ELSE (CASE WHEN CLCOST.CESSIONF=1 THEN 100 ELSE 0 END) END)/100) AS GROSS_LOSS,     

 Case When CLAIM.PCStatus='P' and Month(Claim.CSDate)=MONTH(@P_EDATE) and Year(Claim.CSDate)=Year(@P_EDate) then      
	0    
 else      
  (CLCOST.AMOUNT*(CASE WHEN CLCOST.CONTRIBUTIONF=1 THEN CCALC.SHARE ELSE (CASE WHEN CLCOST.CESSIONF=1 THEN 100 ELSE 0 END) END)/100) 
 End AS GROSS_SETTLED,    
 1 as SETTLEDF,  
 0 as EXPENSE_OS  

FROM CLAIM 
INNER JOIN CCALC ON (CCALC.CNO=CLAIM.CNO) 
LEFT JOIN CLAIM PCLAIM ON (PCLAIM.CNO=CLAIM.PCNO)
INNER JOIN (SELECT CLCOST.CNO, MAX(CAST(CLCOST.ContributionF as Integer)) as CONTRIBUTIONF, MAX(CAST(CLCOST.CESSIONF as Integer)) as CESSIONF, CLCOST.CCTYPE, CLCOST.ID, CLCOST.CURRENCY, SUM(CLCOST.ESTAMOUNT) as ESTIMATE, SUM(CLCOST.AMOUNT) as AMOUNT FROM CLCOST WHERE CLCOST.STATUS='P' GROUP BY CLCOST.CNO, CLCOST.CCTYPE, CLCOST.ID, CLCOST.CURRENCY) CLCOST ON (CLCOST.CNO=CCALC.CNO AND CLCOST.CURRENCY=CCALC.CURRENCY) 
LEFT JOIN (SELECT CLCOST.CNO, MAX(CAST(CLCOST.ContributionF as Integer)) as CONTRIBUTIONF, MAX(CAST(CLCOST.CESSIONF as Integer)) as CESSIONF, CLCOST.CCTYPE, CLCOST.ID, CLCOST.CURRENCY, SUM(CLCOST.ESTAMOUNT) as ESTIMATE, SUM(CLCOST.AMOUNT) as AMOUNT FROM CLCOST WHERE CLCOST.STATUS='P' GROUP BY CLCOST.CNO, CLCOST.CCTYPE, CLCOST.ID, CLCOST.CURRENCY) PCLCOST ON (PCLCOST.CNO=CLAIM.PCNO AND PCLCOST.CCTYPE=CLCOST.CCTYPE AND PCLCOST.ID=CLCOST.ID AND PCLCOST.CURRENCY=CLCOST.CURRENCY)
LEFT JOIN CCALC PCCALC ON (PCCALC.CNO=PCLCOST.CNO AND PCCALC.CURRENCY=PCLCOST.CURRENCY)
INNER JOIN ACCEPTANCE ON (ACCEPTANCE.ANO=CLAIM.ANO) 
WHERE CLAIM.REGDATE<=@P_EDATE AND CLAIM.CTYPE<>'C' AND CLAIM.CSTATUS<>'R'       
AND (CLAIM.PSETTLEDF=0 AND CLAIM.SETTLEDF=1 AND MONTH((Case When Claim.PCStatus='P' then Claim.CSDate else Claim.ADate end))=MONTH(@P_EDATE) and YEAR((Case When Claim.PCStatus='P' then Claim.CSDate else Claim.ADate end))=YEAR(@P_EDATE))                   
AND CLAIM.OCNO NOT IN (SELECT OCNO from @OS_CLAIM)    
RETURN    
End    

