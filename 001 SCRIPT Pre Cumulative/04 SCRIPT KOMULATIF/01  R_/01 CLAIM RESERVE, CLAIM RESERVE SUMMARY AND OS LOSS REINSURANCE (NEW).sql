CREATE FUNCTION CLAIM_CLOSE_BY_DETAIL(@P_SDate as smalldatetime, @P_EDate as  smalldatetime)                    
RETURNS TABLE                     
AS RETURN (                             
SELECT     

Case When ((Claim.Cstatus='C' and Claim.PCStatus='R' and Claim.VSeqNo>1) or (Claim.Cstatus='C' and Claim.PCStatus='P') or (Claim.SettledF=1 and Claim.CStatus='C' and Claim.PCStatus='A')) and Claim.CSDate between @P_SDate and @P_EDate Then Claim.CSDate else Claim.ADate end as Date,
 CLAIM.OCNO, CLLOSS.NOC, CLLOSS.PAYMENT, CLAIM.ANO, CLAIM.CNO AS CCNO, CLAIM.CNO, CCALC.CURRENCY,CLAIM.TOC, ACCEPTANCE.BRANCH, CLAIM.ISTYPE, CLAIM.CLAIMNO,              
