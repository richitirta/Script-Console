CREATE FUNCTION SETTLED_CLAIM_BY_DETAIL( @P_SDate as smalldatetime, @P_EDate as  smalldatetime)      
RETURNS TABLE       
AS RETURN (      
      
SELECT ANO, CNO, CURRENCY, TOC, BRANCH,      
SUM(CURRENT_GROSS_SETTLED-PREVIOUS_GROSS_SETTLED) AS GROSS_SETTLED,      
SUM(CURRENT_NET_SETTLED-PREVIOUS_NET_SETTLED) AS NET_SETTLED      
      
FROM       
(      
SELECT      
 CLAIM.ANO, CLAIM.CNO, CCALC.CURRENCY,COVER.TOC, ACCEPTANCE.BRANCH,      
 0 as PREVIOUS_GROSS_SETTLED,      
 0 as PREVIOUS_NET_SETTLED,      
 ((CCALC.CLAIM+CCALC.COST-CCALC.DEDUCTIBLE-CCALC.SALVAGE-CCALC.SUBROGATION)*CCALC.SHARE/100*(1-CArrHeader.MShare/100)+CCALC.RCOST)+(CCALC.TCOST-CCALC.RCOST-CCALC.COST) as CURRENT_GROSS_SETTLED,      
 ((CCALC.CLAIM+CCALC.COST-CCALC.DEDUCTIBLE-CCALC.SALVAGE-CCALC.SUBROGATION)*CCALC.SHARE/100+CCALC.RCOST)*CARRHEADER.RETENTION/100+(CCALC.TCOST-CCALC.RCOST-CCALC.COST) as CURRENT_NET_SETTLED      
FROM COVER, ACCEPTANCE, CLAIM, CCALC, CARRHEADER      
WHERE CLAIM.CSTATUS in ('A','C') and Claim.CType in ('N','E') and Claim.PCStatus in ('','A') and CLAIM.ADATE BETWEEN @P_SDATE and @P_EDATE AND ACCEPTANCE.ANO=CLAIM.ANO AND COVER.CNO=ACCEPTANCE.CNO AND CCALC.CNO=CLAIM.CNO AND CARRHEADER.CNO=CCALC.CNO      
UNION ALL      
      
SELECT      
 CLAIM.ANO, CLAIM.CNO, CCALC.CURRENCY,COVER.TOC, ACCEPTANCE.BRANCH,      
 ((CCALC.CLAIM+CCALC.COST-CCALC.DEDUCTIBLE-CCALC.SALVAGE-CCALC.SUBROGATION)*CCALC.SHARE/100*(1-CArrHeader.MShare/100)+CCALC.RCOST)+(CCALC.TCOST-CCALC.RCOST-CCALC.COST) as PREVIOUS_GROSS_SETTLED,      
 ((CCALC.CLAIM+CCALC.COST-CCALC.DEDUCTIBLE-CCALC.SALVAGE-CCALC.SUBROGATION)*CCALC.SHARE/100+CCALC.RCOST)*CARRHEADER.RETENTION/100+(CCALC.TCOST-CCALC.RCOST-CCALC.COST) as PREVIOUS_NET_SETTLED,      
 0 as CURRENT_GROSS_SETTLED,      
 0 as CURRENT_NET_SETTLED      
FROM COVER, ACCEPTANCE, CLAIM CCLAIM, CLAIM, CCALC, CARRHEADER      
WHERE CCLAIM.CSTATUS in ('A','C') and CCLAIM.CTYPE in ('C','E') and CCLAIM.PCStatus in ('','A') and CCLAIM.ADATE BETWEEN @P_SDATE and @P_EDATE AND CLAIM.CNO=CCLAIM.PCNO AND ACCEPTANCE.ANO=CLAIM.ANO AND COVER.CNO=ACCEPTANCE.CNO AND CCALC.CNO=CLAIM.CNO AND CARRHEADER.CNO=CCALC.CNO      
) S       
      
GROUP BY ANO, CNO, CURRENCY, TOC, BRANCH      
      
      
)      
               
    
