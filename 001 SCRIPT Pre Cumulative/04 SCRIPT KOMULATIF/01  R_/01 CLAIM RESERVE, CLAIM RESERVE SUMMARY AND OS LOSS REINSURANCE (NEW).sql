from Claim INNER JOIN CLAIM PCLAIM ON (PCLAIM.CNO=CLAIM.PCNO) INNER JOIN CCALC ON (CCALC.CNO=PCLAIM.CNO) 
LEFT JOIN (SELECT CNO, CURRENCY, MAX(NOC) AS NOC, MAX(PAYMENT) AS PAYMENT FROM CLLOSS GROUP BY CNO, CURRENCY) CLLOSS ON (CLLOSS.CNO=PCLAIM.CNO AND CLLOSS.CURRENCY=CCALC.CURRENCY)
INNER JOIN ACCEPTANCE ON (ACCEPTANCE.ANO=PCLAIM.ANO) INNER JOIN CARRHEADER ON (CARRHEADER.CNO=PCLAIM.CNO)        
Where Claim.CStatus in ('C','A') and Claim.CType in ('N','E','C') and Claim.PCstatus in ('','A') and Claim.ADate Between @P_SDate and @P_EDate and Claim.pSettledF=0 and pClaim.CSeqNo<Claim.CSeqNo
