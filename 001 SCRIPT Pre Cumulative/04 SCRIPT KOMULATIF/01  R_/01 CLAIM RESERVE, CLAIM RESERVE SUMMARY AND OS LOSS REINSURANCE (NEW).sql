CREATE FUNCTION OS_CLAIM_BY_DETAIL_LOSS_EXPENSE( @P_EDate as  smalldatetime)                        
RETURNS TABLE                         
AS RETURN (                        
SELECT                        
 CLAIM.OCNO, CLCOST.CCTYPE, CLCOST.ID AS PAYMENT, CLAIM.ANO, CLAIM.CNO, CLCOST.CURRENCY AS CURRENCY,CLAIM.TOC, ACCEPTANCE.BRANCH,CURRENCY.RATE, CLAIM.ISTYPE, CLAIM.CLAIMNO,                  
  
 (CASE                        
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN          
  (CLCOST.ESTIMATE*(CASE WHEN CLCOST.CONTRIBUTIONF=1 THEN CCALC.SHARE ELSE (CASE WHEN CLCOST.CESSIONF=1 THEN 100 ELSE 0 END)  END)/100)
 ELSE                        
  CASE                         
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN          
   (CLCOST.ESTIMATE*(CASE WHEN CLCOST.CONTRIBUTIONF=1 THEN CCALC.SHARE ELSE (CASE WHEN CLCOST.CESSIONF=1 THEN 100 ELSE 0 END) END)/100)-(CASE WHEN PCCALC.CNO IS NOT NULL THEN (PCLCOST.AMOUNT*(CASE WHEN PCLCOST.CONTRIBUTIONF=1 THEN PCCALC.SHARE ELSE (CASE WHEN PCLCOST.CESSIONF=1 THEN 100 ELSE 0 END) END)/100) ELSE 0 END)                        
  ELSE                        
   (CLCOST.ESTIMATE*(CASE WHEN CLCOST.CONTRIBUTIONF=1 THEN CCALC.SHARE ELSE (CASE WHEN CLCOST.CESSIONF=1 THEN 100 ELSE 0 END) END)/100)-(CLCOST.AMOUNT*(CASE WHEN CLCOST.CONTRIBUTIONF=1 THEN CCALC.SHARE ELSE (CASE WHEN CLCOST.CESSIONF=1 THEN 100 ELSE 0 END) END)/100)                      
  END                        
 end) as GROSS_OS,    
                          
 (CLCOST.ESTIMATE*(CASE WHEN CLCOST.CONTRIBUTIONF=1 THEN CCALC.SHARE ELSE (CASE WHEN CLCOST.CESSIONF=1 THEN 100 ELSE 0 END) END)/100) AS GROSS_LOSS,    
                        
 (CASE                        
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE)  OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN                        
  0                         
 ELSE                        
  CASE                         
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN                      
      
   (CASE WHEN PCCALC.CNO IS NOT NULL THEN (PCLCOST.AMOUNT*(CASE WHEN PCLCOST.CONTRIBUTIONF=1 THEN PCCALC.SHARE ELSE (CASE WHEN PCLCOST.CESSIONF=1 THEN 100 ELSE 0 END) END)/100) ELSE 0 END)                        
  ELSE                        
   (CLCOST.AMOUNT*(CASE WHEN CLCOST.CONTRIBUTIONF=1 THEN CCALC.SHARE ELSE (CASE WHEN CLCOST.CESSIONF=1 THEN 100 ELSE 0 END) END)/100)                      
  END                        
 end) as GROSS_SETTLED,

    
(CASE                        
 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN          
  (CLCOST.ESTIMATE*(CASE WHEN CLCOST.CONTRIBUTIONF=0 THEN 100 ELSE 0 END)/100)
 ELSE                        
  CASE                         
  WHEN (CLAIM.CSTATUS in ('P','T')) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) THEN          
   (CLCOST.ESTIMATE*(CASE WHEN CLCOST.CONTRIBUTIONF=0 THEN 100 ELSE 0 END)/100)-(CASE WHEN PCCALC.CNO IS NOT NULL THEN (PCLCOST.AMOUNT*(CASE WHEN PCLCOST.CONTRIBUTIONF=0 THEN 100 ELSE 0 END)/100) ELSE 0 END)                        
  ELSE                        
   (CLCOST.ESTIMATE*(CASE WHEN CLCOST.CONTRIBUTIONF=0 THEN 100 ELSE 0 END)/100)-(CLCOST.AMOUNT*(CASE WHEN CLCOST.CONTRIBUTIONF=0 THEN 100 ELSE 0 END)/100)                      
  END                        
 end) as EXPENSE_OS
           
FROM CLAIM 
INNER JOIN CCALC ON (CCALC.CNO=CLAIM.CNO) 
LEFT JOIN CLAIM PCLAIM ON (PCLAIM.CNO=CLAIM.PCNO)
INNER JOIN (SELECT CLCOST.CNO, MAX(CAST(CLCOST.ContributionF as Integer)) as CONTRIBUTIONF, MAX(CAST(CLCOST.CESSIONF as Integer)) as CESSIONF, CLCOST.CCTYPE, CLCOST.ID, CLCOST.CURRENCY, SUM(CLCOST.ESTAMOUNT) as ESTIMATE, SUM(CLCOST.AMOUNT) as AMOUNT FROM CLCOST WHERE CLCOST.STATUS='P' GROUP BY CLCOST.CNO, CLCOST.CCTYPE, CLCOST.ID, CLCOST.CURRENCY) CLCOST ON (CLCOST.CNO=CCALC.CNO AND CLCOST.CURRENCY=CCALC.CURRENCY) 
LEFT JOIN (SELECT CLCOST.CNO, MAX(CAST(CLCOST.ContributionF as Integer)) as CONTRIBUTIONF, MAX(CAST(CLCOST.CESSIONF as Integer)) as CESSIONF, CLCOST.CCTYPE, CLCOST.ID, CLCOST.CURRENCY, SUM(CLCOST.ESTAMOUNT) as ESTIMATE, SUM(CLCOST.AMOUNT) as AMOUNT FROM CLCOST WHERE CLCOST.STATUS='P' GROUP BY CLCOST.CNO, CLCOST.CCTYPE, CLCOST.ID, CLCOST.CURRENCY) PCLCOST ON (PCLCOST.CNO=CLAIM.PCNO AND PCLCOST.CCTYPE=CLCOST.CCTYPE AND PCLCOST.ID=CLCOST.ID AND PCLCOST.CURRENCY=CLCOST.CURRENCY)
LEFT JOIN CCALC PCCALC ON (PCCALC.CNO=PCLCOST.CNO AND PCCALC.CURRENCY=PCLCOST.CURRENCY)
INNER JOIN ACCEPTANCE ON (ACCEPTANCE.ANO=CLAIM.ANO) 
INNER JOIN fn_exchange(@P_EDate) as Currency On (Currency.Currency=CCalc.Currency)            
