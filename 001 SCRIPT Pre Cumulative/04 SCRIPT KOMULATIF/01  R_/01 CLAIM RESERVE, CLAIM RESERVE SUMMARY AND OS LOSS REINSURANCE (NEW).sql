LEFT JOIN (SELECT CNO, ID, CURRENCY, SUM(ESTAMOUNT) AS ESTAMOUNT, SUM(AMOUNT) AS AMOUNT FROM CLDED GROUP BY CNO, ID, CURRENCY) PCLDED ON (PCLDED.CNO=CLAIM.PCNO AND PCLDED.ID=PCLLOSS.PAYMENT AND PCLDED.CURRENCY=PCLLOSS.CURRENCY AND PCLDED.ID=PCLLOSS.PAYMENT)
