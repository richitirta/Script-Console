 When (CLAIM.CSEQNO=0 OR PCLAIM.CTYPE='C') AND ((CLAIM.CSTATUS IN ('P','T') AND CLAIM.CSDATE<=@P_EDATE) OR (CLAIM.CSTATUS IN ('A') AND CLAIM.ADATE>@P_EDATE) OR (CLAIM.CSTATUS IN ('C') AND (CASE WHEN CLAIM.ADATE IS NOT NULL AND CLAIM.PCSTATUS<>'P' THEN CLAIM.ADATE ELSE CLAIM.CSDATE END)>@P_EDATE) ) THEN          
