  Claim.ADate as Date, PCLAIM.OCNO, CLLOSS.NOC, CLLOSS.PAYMENT, PCLAIM.ANO, CLAIM.CNO AS CCNO, PCLAIM.CNO, CCALC.CURRENCY, CCALC.RATE, PCLAIM.TOC, ACCEPTANCE.BRANCH, PCLAIM.ISTYPE, PCLAIM.CLAIMNO,                      
