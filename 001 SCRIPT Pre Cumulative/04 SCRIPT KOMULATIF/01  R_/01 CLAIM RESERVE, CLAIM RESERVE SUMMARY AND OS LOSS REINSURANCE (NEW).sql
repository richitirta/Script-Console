Create FUNCTION R_OS_CLAIM( @P_EDate as  smalldatetime)              
RETURNS @OS_CLAIM TABLE (OCNO int, Payment Varchar(10), ANO int, CNO int, CURRENCY varchar(10), TOC varchar(10), Branch Varchar(10), ISType varchar(1), ClaimNo varchar(20), GROSS_OS Float, GROSS_LOSS float, GROSS_SETTLED float, SETTLEDF bit,EXPENSE_OS Float)  
AS  
BEGIN  
  
insert into @OS_Claim      
SELECT OCNO, PAYMENT, ANO, CNO, CURRENCY, TOC, BRANCH, ISTYPE, CLAIMNO, GROSS_OS, GROSS_LOSS, GROSS_SETTLED, 0 as SETTLEDF, EXPENSE_OS
FROM OS_CLAIM_BY_DETAIL(@P_EDATE)      
  
  
insert into @OS_Claim          
Select       
 CLAIM.OCNO, CLAIM.PAYMENT, CLAIM.ANO, CLAIM.CNO, CCALC.CURRENCY,CLAIM.TOC, ACCEPTANCE.BRANCH, CLAIM.ISTYPE, CLAIM.CLAIMNO,        
 0 as GROSS_OS,    
 ((CCALC.LOSS-CCALC.EDEDUCTIBLE+CCALC.ECOST-CCALC.SALVAGE-CCALC.SUBROGATION)*CCALC.SHARE/100+CCALC.ERCOST) AS GROSS_LOSS,       
 (Case When PCStatus='P' and Month(Claim.CSDate)=MONTH(@P_EDATE) and Year(Claim.CSDate)=Year(@P_EDate) then    
 0  
 else    
  ((CCALC.CLAIM-CCALC.DEDUCTIBLE+CCALC.COST-CCALC.SALVAGE-CCALC.SUBROGATION)*CCALC.SHARE/100+CCALC.RCOST) End) AS GROSS_SETTLED,  
 1 as SETTLEDF,
 0 as EXPENSE_OS
FROM CLAIM INNER JOIN CCALC ON (CCALC.CNO=CLAIM.CNO) LEFT JOIN CCALC PCCALC ON (PCCALC.CNO=CLAIM.PCNO AND PCCALC.CURRENCY=CCALC.CURRENCY)              
     INNER JOIN ACCEPTANCE ON (ACCEPTANCE.ANO=CLAIM.ANO)    
WHERE CLAIM.REGDATE<=@P_EDATE AND CLAIM.CTYPE<>'C' AND CLAIM.CSTATUS<>'R'     
AND (CLAIM.PSETTLEDF=0 AND CLAIM.SETTLEDF=1 AND MONTH((Case When Claim.PCStatus='P' then Claim.CSDate else Claim.ADate end))=MONTH(@P_EDATE) and YEAR((Case When Claim.PCStatus='P' then Claim.CSDate else Claim.ADate end))=YEAR(@P_EDATE))                 
AND OCNO NOT IN (SELECT OCNO from @OS_CLAIM)  
RETURN  
End  
    

