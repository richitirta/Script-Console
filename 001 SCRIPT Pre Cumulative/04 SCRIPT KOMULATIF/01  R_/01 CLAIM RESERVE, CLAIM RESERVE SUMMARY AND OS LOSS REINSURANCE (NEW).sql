- (CASE WHEN Claim.SettledF=1 and Claim.Cstatus in ('C','A') and Claim.PCStatus in ('','A') and Claim.CType in ('N','E') Then ((CCALC.CLAIM-CCALC.DEDUCTIBLE+CCALC.COST-CCALC.SALVAGE-CCALC.SUBROGATION)*CCALC.SHARE/100*(100-CARRHEADER.MSHARE)/100+CCALC.RCOST+CCALC.TCOST-CCALC.COST-CCALC.RCOST) else 0 end)  AS CLAIM_CLOSE,    
(((CCALC.LOSS-CCALC.EDEDUCTIBLE+CCALC.ECOST-CCALC.SALVAGE-CCALC.SUBROGATION)*CCALC.SHARE/100+CCALC.ERCOST)*(CARRHEADER.ERETENTION/100)+CCALC.ETCOST-CCALC.ECOST-CCALC.ERCOST)     
