'ALLOWPRECEDEFAC','ALLOWOTHERBIZSRC','ALLOWZEROESTIMATE','ALLOWCHANGEREFNO','ALLOWCHANGEBRANCH')
and 1 not in(Select 1 from SysUserForm S1 Where S1.type=S.type and S1.fname=f.fname)





