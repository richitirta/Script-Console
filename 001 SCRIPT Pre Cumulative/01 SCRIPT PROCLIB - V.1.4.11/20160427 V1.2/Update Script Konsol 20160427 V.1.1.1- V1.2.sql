SUM(RARRHEADER.DAmount / (RARRHEADER.PctShare / 100 * RARRHEADER.PCTLOSS/100 * (100 - RARRHEADER.MShare) / 100)) As REGAMOUNT,   
SUM(RARRHEADER.DAmount / (RARRHEADER.PctShare / 100 * RARRHEADER.PCTLOSS/100 * (100 - RARRHEADER.MShare) / 100)/(CASE WHEN RECLASS.CESSIONF=1 THEN RARRHEADER.CLIMIT ELSE 1 END)) As Amount   
From RARRHEADER, acceptance, REINSURANCE, cover, RECLASS   
WHERE COVER.CNO=ACCEPTANCE.CNO AND RECLASS.TOC=COVER.TOC AND RECLASS.RNO=REINSURANCE.RNO AND   
ACCEPTANCE.REGID=@P_REGID AND ACCEPTANCE.FLDID=@P_FLDID And ACCEPTANCE.VALUEID=@P_VALUEID And ACCEPTANCE.ANO=RARRHEADER.ANO and ACCEPTANCE.ASTATUS='W' and RArrHeader.Status='A' And REINSURANCE.RID=RARRHEADER.DID   
And (CASE WHEN RECLASS.CESSIONF=1 THEN RARRHEADER.CLIMIT ELSE 1 END)<>0   
GROUP BY YEAR(RARRHEADER.RDATE)   
ORDER BY MIN(CASE WHEN RECLASS.LIMIT<>0 THEN RECLASS.LIMIT ELSE REINSURANCE.LIMIT END*CASE WHEN (Cover.ISType<>'R' and Cover.ISType<>'T') or  (ReClass.DirectF=0) Then 1 Else 0 End) DESC   
   
