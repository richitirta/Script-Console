	And (Claim.ISType in ('I','L') or (Claim.ISType in ('C') and CLCOST.ContributionF=0))
	And CLCOST.ApplyCoShareF=1
	) CoShare
WHERE CLCOST.CNO=@P_CNO AND CLCOST.STATUS='P' 
 
Union All 
 
