CREATE FUNCTION FN_GENHTAB (@P_FLDID as varchar(10), @P_SEGMENT as varchar(10))     
RETURNS Table
AS RETURN (

Select 
G1.FLDTAB, 
Case when G1.FLDCOM=1 Then G1.FLDCOM Else coalesce(G2.FLDCOM, cast(0 as Bit)) End as FLDCOM,
Case when G1.FLDCOMA=1 Then G1.FLDCOMA Else coalesce(G2.FLDCOMA, cast(0 as Bit)) End as FLDCOMA,
G1.FLDDFORMAT,
G1.FLDIFORMAT,
G1.FLDTYPE,
G1.SUBLINKF, 
G1.FLDSEARCH,
G1.FLDCRITERIA,
G1.FLDCHGINF,
G1.FLDLOWER,
G1.FLDUPPER,
G1.FLDREGEX,
G1.FLDFUNC,
G1.FLDMAP,
G1.FLDENCRYPTF,
G1.FLDID1
from GenHTab G1
Outer Apply (Select Top 1 G2.FLDCOM, G2.FLDCOMA from GenHSegment G2 Where G2.FLDID=G1.FLDID and (G2.SEGMENT='<All>' or G2.SEGMENT=@P_SEGMENT)) G2
Where G1.FLDID=@P_FLDID
)

GO

