DROP FUNCTION QCLAIM_CCALC
GO
CREATE FUNCTION QCLAIM_CCALC ()    
RETURNS TABLE AS    
RETURN (    
SELECT  CLAIM.CNO,    
 SUM(CCALC.LOSS*CCALC.RATE*CCALC.SHARE/100) AS LOSS,    
 SUM(CCALC.CLAIM*CCALC.RATE*CCALC.SHARE/100) AS CLAIM,    
 SUM(CCALC.DEDUCTIBLE*CCALC.RATE*CCALC.SHARE/100) AS DEDUCTIBLE,    
 SUM(CCALC.COST*CCALC.RATE*CCALC.SHARE/100+CCALC.RCOST*CCALC.RATE+(CCALC.TCOST-CCALC.COST-CCALC.RCOST)*CCALC.RATE) AS COST,    
 SUM(CCALC.ECOST*CCALC.RATE*CCALC.SHARE/100+CCALC.ERCOST*CCALC.RATE+(CCALC.ETCOST-CCALC.ECOST-CCALC.ERCOST)*CCALC.RATE) AS ECOST,    
 SUM(CCALC.SUBROGATION*CCALC.RATE*CCALC.SHARE/100+CCALC.RSUBROGATION*CCALC.RATE+(CCALC.TSUBROGATION-CCALC.SUBROGATION-CCALC.RSUBROGATION)*CCALC.RATE) AS SUBROGATION,    
 SUM(CCALC.ESUBROGATION*CCALC.RATE*CCALC.SHARE/100+CCALC.ERSUBROGATION*CCALC.RATE+(CCALC.ETSUBROGATION-CCALC.ESUBROGATION-CCALC.ERSUBROGATION)*CCALC.RATE) AS ESUBROGATION,
 SUM(CCALC.SALVAGE*CCALC.RATE*CCALC.SHARE/100+CCALC.RSALVAGE*CCALC.RATE+(CCALC.TSALVAGE-CCALC.SALVAGE-CCALC.RSALVAGE)*CCALC.RATE) AS SALVAGE,    
 SUM(CCALC.ESALVAGE*CCALC.RATE*CCALC.SHARE/100+CCALC.ERSALVAGE*CCALC.RATE+(CCALC.ETSALVAGE-CCALC.ESALVAGE-CCALC.ERSALVAGE)*CCALC.RATE) AS ESALVAGE,
 SUM( 
 CASE    
 WHEN CLAIM.CTYPE='C' OR (CLAIM.PCSTATUS<>'') OR (CLAIM.SETTLEDF=1) THEN ---CLAIM CANCEL OR CLAIM CLOSE OR FULLY SETTLED
	0
 WHEN CLAIM.CSTATUS IN ('R','P','T') THEN
	coalesce((((CCALC.LOSS-CCALC.EDEDUCTIBLE-CCALC.ESALVAGE+CCALC.ECOST-CCALC.ESUBROGATION)*CCALC.SHARE/100+CCALC.ERCOST-CCALC.ERSUBROGATION-CCALC.ERSALVAGE+(CCALC.ETCOST-CCALC.ECOST-CCALC.ERCOST)-(CCALC.ETSUBROGATION-CCALC.ESUBROGATION-CCALC.ERSUBROGATION)-(CCALC.ETSALVAGE-CCALC.ESALVAGE-CCALC.ERSALVAGE))*CCALC.RATE),0)
    -
	coalesce((((PCCALC.CLAIM-PCCALC.DEDUCTIBLE-PCCALC.SALVAGE+PCCALC.COST-PCCALC.SUBROGATION)*PCCALC.SHARE/100+PCCALC.RCOST-PCCALC.RSUBROGATION-PCCALC.RSALVAGE+(PCCALC.TCOST-PCCALC.COST-PCCALC.RCOST)-(PCCALC.TSUBROGATION-PCCALC.SUBROGATION-PCCALC.RSUBROGATION)-(PCCALC.TSALVAGE-PCCALC.SALVAGE-PCCALC.RSALVAGE))*PCCALC.RATE),0)
 WHEN CLAIM.CSTATUS NOT IN ('R','P','T') THEN
	coalesce((((CCALC.LOSS-CCALC.EDEDUCTIBLE-CCALC.ESALVAGE+CCALC.ECOST-CCALC.ESUBROGATION)*CCALC.SHARE/100+CCALC.ERCOST-CCALC.ERSUBROGATION-CCALC.ERSALVAGE+(CCALC.ETCOST-CCALC.ECOST-CCALC.ERCOST)-(CCALC.ETSUBROGATION-CCALC.ESUBROGATION-CCALC.ERSUBROGATION)-(CCALC.ETSALVAGE-CCALC.ESALVAGE-CCALC.ERSALVAGE))*CCALC.RATE),0)
    -
	coalesce((((CCALC.CLAIM-CCALC.DEDUCTIBLE-CCALC.SALVAGE+CCALC.COST-CCALC.SUBROGATION)*CCALC.SHARE/100+CCALC.RCOST-CCALC.RSUBROGATION-CCALC.RSALVAGE+(CCALC.TCOST-CCALC.COST-CCALC.RCOST)-(CCALC.TSUBROGATION-CCALC.SUBROGATION-CCALC.RSUBROGATION)-(CCALC.TSALVAGE-CCALC.SALVAGE-CCALC.RSALVAGE))*CCALC.RATE),0)
 ELSE 0 END
 ) AS RESERVED  
FROM  Claim 
LEFT JOIN CCALC ON (CCALC.CNO=CLAIM.CNO)
LEFT JOIN CCALC PCCALC ON (CLAIM.CSEQNO>0 AND PCCALC.CNO=CLAIM.PCNO AND PCCALC.CURRENCY=CCALC.CURRENCY)
GROUP BY CLAIM.CNO    

)    



go






