CREATE PROCEDURE [dbo].[QAccRegAmount_A] (@PANO as Integer)   
AS  
SELECT SUM(COALESCE(R1.AMOUNT, COALESCE(R2.AMOUNT, R3.AMOUNT))) AS AMOUNT
FROM ACCEPTANCE
OUTER APPLY (SELECT R.ANO, R.AAMOUNT-R.CAAMOUNT AS AMOUNT FROM RARRHEADER R Where R.ANO=ACCEPTANCE.ANO AND R.STATUS='A') R1
OUTER APPLY (SELECT R.ANO, R.AAMOUNT-R.CAAMOUNT AS AMOUNT FROM RARRHEADER R Where R.ANO=ACCEPTANCE.PANO AND R.STATUS='A') R2
OUTER APPLY (SELECT R.ANO, R.AAMOUNT-R.CAAMOUNT AS AMOUNT FROM RARRHEADER R Where R.ANO=ACCEPTANCE.RANO AND R.STATUS='A') R3
CROSS APPLY (SELECT ANO from ACCEPTANCE PACCEPTANCE Where PACCEPTANCE.ANO=COALESCE(R1.ANO, COALESCE(R2.ANO, R3.ANO)) AND PACCEPTANCE.REGID=ACCEPTANCE.REGID AND PACCEPTANCE.FLDID=ACCEPTANCE.FLDID AND PACCEPTANCE.VALUEID=ACCEPTANCE.VALUEID) PACCEPTANCE
WHERE ACCEPTANCE.ANO=@PANO AND ACCEPTANCE.FLDID<>'' and ACCEPTANCE.VALUEID<>'' 


GO

