DROP PROCEDURE QAccRegAmount_A 
GO
CREATE PROCEDURE QAccRegAmount_A (@PANO as Integer)   
AS  
SELECT SUM(COALESCE(R1.AMOUNT, COALESCE(R2.AMOUNT, R3.AMOUNT))) AS AMOUNT
FROM ACCEPTANCE
OUTER APPLY (SELECT R.AAMOUNT-R.CAAMOUNT AS AMOUNT FROM RARRHEADER R Where R.ANO=ACCEPTANCE.ANO AND R.STATUS='A') R1
OUTER APPLY (SELECT R.AAMOUNT-R.CAAMOUNT AS AMOUNT FROM RARRHEADER R, ACCEPTANCE PA Where PA.ANO=ACCEPTANCE.PANO AND R.ANO=PA.ANO AND PA.REGID=ACCEPTANCE.REGID AND PA.FLDID=ACCEPTANCE.FLDID AND PA.VALUEID=ACCEPTANCE.VALUEID AND R.STATUS='A') R2
OUTER APPLY (SELECT R.AAMOUNT-R.CAAMOUNT AS AMOUNT FROM RARRHEADER R, ACCEPTANCE PA Where PA.ANO=ACCEPTANCE.RANO AND R.ANO=PA.ANO AND PA.REGID=ACCEPTANCE.REGID AND PA.FLDID=ACCEPTANCE.FLDID AND PA.VALUEID=ACCEPTANCE.VALUEID AND R.STATUS='A') R3
WHERE ACCEPTANCE.ANO=@PANO AND ACCEPTANCE.FLDID<>'' and ACCEPTANCE.VALUEID<>'' 

GO

